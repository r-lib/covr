# Rust code in packages is compiled by cargo into a static library, which is
# linked into the package's shared object. Its coverage is measured with LLVM's
# source-based coverage (`-C instrument-coverage`): each process writes its
# counts to a `.profraw` file when it exits, which are merged with
# `llvm-profdata` and read with `llvm-cov export`.

# The paths of the package's `Cargo.toml` files relative to `src/`, or none if
# it has no Rust code.
rust_manifests <- function(path) {
  manifests <- list.files(
    file.path(path, "src"),
    pattern = "^Cargo[.]toml$",
    recursive = TRUE
  )
  manifests[!in_rust_dependency_dir(manifests)]
}

# Are the paths in a directory of vendored crates, a CARGO_HOME, or cargo's
# build output (e.g. code generated by build scripts)? These aren't the
# package's own code. Paths are relative, or in one of the `roots`.
in_rust_dependency_dir <- function(paths, roots = NULL) {
  for (root in roots) {
    paths <- sub(rex::rex(start, root, "/"), "", paths)
  }
  grepl("(^|/)(vendor|target|[.]cargo)/", paths)
}

# Packages with Rust code can also compile the C code of the crates they
# vendor (e.g. with the cc crate), whose coverage gcov then measures. Drop the
# coverage of the files of Rust dependencies in the `roots`.
drop_rust_dependencies <- function(coverage, roots) {
  files <- vcapply(coverage, function(x) {
    get_source_filename(x$srcref, full.names = TRUE)
  })
  coverage[!in_rust_dependency_dir(files, roots)]
}

# Find the tools needed to measure the coverage of the package's Rust code, and
# the build options and environment for it, which keep their files in `dir`.
# Returns `NULL` if `options(covr.llvm_cov = "")` turns this off, or the tools
# can't be found, which gives a warning.
rust_coverage_setup <- function(path, dir) {
  if (identical(getOption("covr.llvm_cov"), "")) {
    return(NULL)
  }
  if (is_windows()) {
    covr_warn(c(
      "Can't measure the coverage of Rust code on Windows.",
      i = "Use {.code options(covr.llvm_cov = \"\")} to turn this off."
    ))
    return(NULL)
  }

  # Packages run cargo in `src/`, so a `rust-toolchain.toml` there or above
  # selects the toolchain that builds the code.
  toolchain <- rust_toolchain(file.path(path, "src"))
  llvm_cov <- getOption("covr.llvm_cov") %||% toolchain$llvm_cov
  llvm_profdata <- getOption("covr.llvm_profdata") %||% toolchain$llvm_profdata

  missing <- c(
    rustc = is.null(toolchain$rustc),
    "the Rust profiler runtime" = is.null(toolchain$profiler_runtime),
    "llvm-cov" = is.null(llvm_cov),
    "llvm-profdata" = is.null(llvm_profdata)
  )
  if (any(missing)) {
    llvm_tools <- any(missing[c("llvm-cov", "llvm-profdata")])
    rustup <- toolchain$rustup_toolchain
    llvm_version <- toolchain$llvm_version %||% NA_character_
    missing <- names(missing)[missing]
    covr_warn(c(
      "Can't measure the coverage of Rust code.",
      x = "Can't find {missing}.",
      i = if (llvm_tools && !is.null(rustup)) {
        "Install the llvm tools with
        {.code rustup component add llvm-tools --toolchain {rustup}}."
      } else if (llvm_tools) {
        "Install the llvm tools with {.code rustup component add llvm-tools}."
      },
      i = if (llvm_tools && is.null(rustup) && !is.na(llvm_version)) {
        "If Rust isn't installed with rustup, install those of LLVM {llvm_version}."
      },
      i = "Use {.code options(covr.llvm_cov = \"\")} to turn this off."
    ))
    return(NULL)
  }

  # The runtime that writes the counts isn't included in the static library.
  # On Linux the instrumented code doesn't refer to it either, so the linker
  # needs to be told to include it.
  libs <- shQuote(toolchain$profiler_runtime)
  if (identical(Sys.info()[["sysname"]], "Linux")) {
    libs <- c("-Wl,-u,__llvm_profile_runtime", libs)
  }

  # The wrapper is kept in `dir`, which must stay the same for cargo to reuse
  # the crates it compiled with it, as the wrapper's path is part of the hash
  # in their file names.
  profiles <- file.path(dir, "profiles")
  dir.create(profiles, recursive = TRUE, showWarnings = FALSE)

  list(
    sysroot = toolchain$sysroot,
    llvm_cov = llvm_cov,
    llvm_profdata = llvm_profdata,
    libs = paste(libs, collapse = " "),
    build_dir = dir,
    build_env = c(
      RUSTC_WORKSPACE_WRAPPER = rust_coverage_wrapper(dir, toolchain$sysroot),
      # The counts written while the package is built, by instrumented build
      # scripts and proc macros and the loading test of `R CMD INSTALL`, which
      # aren't wanted
      LLVM_PROFILE_FILE = file.path(dir, "build_profiles", "%p-%m.profraw")
    ),
    profiles = profiles,
    env = c(LLVM_PROFILE_FILE = file.path(profiles, "%p-%m.profraw"))
  )
}

# Write a script in `dir` that cargo runs instead of rustc for the crates of
# the package's workspace (with `RUSTC_WORKSPACE_WRAPPER`), which instruments
# them. Packages set `RUSTFLAGS` in many ways, from their Makevars, configure
# scripts or cargo's configuration, which a wrapper doesn't interfere with,
# and their dependencies are built as without covr. The code is only
# instrumented if it's compiled by the toolchain with `sysroot`, whose
# profiler runtime is linked into the package; the script logs this for each
# crate it compiles in `rustc.log` (see `rust_check_build()`).
rust_coverage_wrapper <- function(dir, sysroot) {
  wrapper <- file.path(dir, "rustc")
  # A wrapper the user has set already runs rustc
  existing <- Sys.getenv("RUSTC_WORKSPACE_WRAPPER")
  writeLines(
    c(
      "#!/bin/sh",
      sprintf(
        "if [ \"$(\"$1\" --print sysroot 2>/dev/null)\" = %s ]; then",
        shQuote(sysroot)
      ),
      "  set -- \"$@\" -C instrument-coverage",
      "  compiled=instrumented",
      "else",
      "  compiled=skipped",
      "fi",
      "case \" $* \" in",
      sprintf(
        "  *\" --crate-name \"*) echo \"$compiled $1\" >> %s ;;",
        shQuote(file.path(dir, "rustc.log"))
      ),
      "esac",
      paste("exec", if (nzchar(existing)) shQuote(existing), "\"$@\"")
    ),
    wrapper
  )
  Sys.chmod(wrapper, "755")
  wrapper
}

# After the package is built, check that cargo compiled its crates with the
# instrumentation, and discard the counts written while building. Returns
# `rust`, or `NULL` with a warning if it didn't. The log is kept between the
# builds of the instrumented copy of a package loaded with
# pkgload::load_all(), where cargo only compiles the crates that changed, so
# the crate compiled last tells how they were built.
rust_check_build <- function(rust) {
  unlink(file.path(rust$build_dir, "build_profiles"), recursive = TRUE)
  log <- file.path(rust$build_dir, "rustc.log")
  compiled <- if (file.exists(log)) readLines(log) else character()
  last <- c("", compiled)[[length(compiled) + 1]]
  if (startsWith(last, "instrumented ")) {
    return(rust)
  }
  rustc <- sub("^skipped ", "", last)
  covr_warn(c(
    "Can't measure the coverage of Rust code.",
    x = if (rustc != last) {
      "It was compiled by {.file {rustc}}, from another toolchain than
      {.path {rust$sysroot}}."
    } else {
      "cargo didn't compile it, e.g. because the package used a prebuilt
      library."
    }
  ))
  NULL
}

# Add the libraries needed for Rust coverage to the flags in `covr.flags`.
add_rust_flags <- function(flags, rust) {
  if (is.null(rust)) {
    return(flags)
  }
  libs <- names(flags) == "PKG_LIBS"
  c(
    flags[!libs],
    PKG_LIBS = paste(c(flags[libs], rust$libs), collapse = " ")
  )
}

# The counts of Rust code are written when the process exits, or when its DLL
# is unloaded, which doesn't happen on macOS, as Rust's thread-local variables
# keep the DLL loaded, nor on Linux once the code used thread-local variables
# with destructors. To measure the coverage of Rust code in the current
# session, this compiles an object to link into the DLL, which exports a
# function that writes them (see `write_llvm_profile()`). Returns `rust` with
# the object added to its libraries.
add_llvm_profile_writer <- function(rust) {
  object <- file.path(rust$build_dir, "covr_llvm_profile_write.o")
  if (!file.exists(object)) {
    source <- sub("[.]o$", ".c", object)
    writeLines(
      c(
        "int __llvm_profile_write_file(void);",
        "void __llvm_profile_set_filename(const char *);",
        "int covr_llvm_profile_write(void) {",
        "  int status = __llvm_profile_write_file();",
        # The runtime writes the counts again when the DLL is unloaded or the
        # process exits, which then go nowhere. After `__llvm_profile_dump()`
        # it would print a note instead.
        "  __llvm_profile_set_filename(\"/dev/null\");",
        "  return status;",
        "}"
      ),
      source
    )
    system_output(r_binary(), c("CMD", "COMPILE", source), quiet = TRUE)
  }
  # Before the profiler runtime, which defines the functions it calls
  rust$libs <- paste(shQuote(object), rust$libs)
  rust
}

# Writes the counts of the Rust code in the loaded DLL at `path`, if it was
# linked with the object of `add_llvm_profile_writer()`.
write_llvm_profile <- function(path) {
  invisible(.Call(covr_write_llvm_profile, path))
}

find_rustc <- function() {
  path <- unname(Sys.which("rustc"))
  if (nzchar(path)) {
    return(path)
  }
  # Packages typically add cargo's default location to the `PATH` when they
  # build, so look there too.
  cargo_home <- Sys.getenv(
    "CARGO_HOME",
    file.path(Sys.getenv("HOME"), ".cargo")
  )
  path <- file.path(cargo_home, "bin", "rustc")
  if (file.exists(path)) path
}

# The paths of rustc, the profiler runtime and the llvm tools matching rustc's
# LLVM, with `NULL` for those that can't be found, and the rustup toolchain.
rust_toolchain <- function(dir) {
  rustc <- find_rustc()
  if (is.null(rustc)) {
    return(list())
  }
  rustc_output <- function(args) {
    tryCatch(
      withr::with_dir(dir, system_output(rustc, args, quiet = TRUE)),
      error = function(e) character()
    )
  }
  existing <- function(path) {
    path <- path[file.exists(path)]
    if (length(path)) path[[1]]
  }

  sysroot <- rustc_output(c("--print", "sysroot"))
  version <- rustc_output("-vV")
  host <- sub("^host: ", "", grep("^host: ", version, value = TRUE))
  if (length(sysroot) != 1 || length(host) != 1) {
    return(list(rustc = rustc))
  }
  target_libdir <- rustc_output(c("--print", "target-libdir"))
  llvm_major <- llvm_major_version(version)

  # rustup installs the llvm tools in the toolchain with
  # `rustup component add llvm-tools`. The Rust of Linux distributions uses
  # the system's LLVM, whose tools are installed separately.
  bin <- file.path(sysroot, "lib", "rustlib", host, "bin")
  llvm_tool <- function(name) {
    existing(file.path(bin, name)) %||% system_llvm_tool(name, llvm_major)
  }

  list(
    rustc = rustc,
    sysroot = sysroot,
    # e.g. the toolchain pinned by a `rust-toolchain.toml`
    rustup_toolchain = if (basename(dirname(sysroot)) == "toolchains") {
      basename(sysroot)
    },
    profiler_runtime = existing(Sys.glob(file.path(
      target_libdir,
      "libprofiler_builtins-*.rlib"
    ))),
    llvm_cov = llvm_tool("llvm-cov"),
    llvm_profdata = llvm_tool("llvm-profdata"),
    llvm_version = llvm_major
  )
}

# The major version in the `LLVM version` line of `rustc -vV` or
# `llvm-cov --version`, or `NA`.
llvm_major_version <- function(version) {
  version <- grep("LLVM version:? [0-9]+", version, value = TRUE)
  if (!length(version)) {
    return(NA_character_)
  }
  sub(".*LLVM version:? ([0-9]+).*", "\\1", version[[1]])
}

# An llvm tool of the system's LLVM with the major version `major`, which must
# match rustc's for the tools to read its counts: `llvm-cov-18` (as named by
# Debian and Ubuntu), or `llvm-cov` if it has the same version (e.g. Fedora).
system_llvm_tool <- function(name, major) {
  if (is.na(major)) {
    return(NULL)
  }
  path <- unname(Sys.which(paste0(name, "-", major)))
  if (nzchar(path)) {
    return(path)
  }
  path <- unname(Sys.which(name))
  if (!nzchar(path)) {
    return(NULL)
  }
  version <- tryCatch(
    system_output(path, "--version", quiet = TRUE),
    error = function(e) character()
  )
  if (identical(llvm_major_version(version), major)) path
}

# Run one of the llvm tools, returning its standard output. Gives a warning with
# the tool's error output and returns `NULL` if it fails, unless its output
# matches `empty`, which returns no output.
llvm_tool_run <- function(tool, args, quiet = TRUE, empty = NULL) {
  if (!quiet) {
    message(wrap_command(command_line(tool, args)))
  }
  res <- run_command(tool, args)
  output <- res$stdout
  errors <- res$stderr
  if (!quiet && length(errors)) {
    message(paste(errors, collapse = "\n"))
  }
  status <- res$status
  if (status != 0L) {
    if (!is.null(empty) && any(grepl(empty, errors, ignore.case = TRUE))) {
      return(character())
    }
    covr_warn(
      c(
        "Can't measure the coverage of Rust code.",
        x = "{.file {basename(tool)}} failed with exit status {status}.",
        i = if (length(errors)) "Its output:"
      ),
      output = errors
    )
    return(NULL)
  }
  output
}

# Merge the counts written by the processes that ran the package's code, and
# read the coverage of its Rust code from its shared `objects`.
run_llvm_cov <- function(rust, path, objects, quiet = TRUE) {
  profiles <- list.files(
    rust$profiles,
    pattern = "[.]profraw$",
    full.names = TRUE
  )
  if (!length(profiles)) {
    covr_warn("Can't find any coverage of Rust code.")
    return()
  }

  inputs <- file.path(rust$profiles, "inputs.txt")
  writeLines(profiles, inputs)
  profdata <- file.path(rust$profiles, "coverage.profdata")
  merged <- llvm_tool_run(
    rust$llvm_profdata,
    c("merge", "-sparse", paste0("--input-files=", inputs), "-o", profdata),
    quiet = quiet
  )
  if (is.null(merged)) {
    return()
  }

  lcov <- llvm_tool_run(
    rust$llvm_cov,
    c(
      "export",
      "-format=lcov",
      paste0("-instr-profile=", profdata),
      objects[[1]],
      sprintf("-object=%s", objects[-1])
    ),
    quiet = quiet,
    # The package's own crates can have no code in the shared object, e.g. if
    # it only exports the API of a dependency (like gifski's)
    empty = "no coverage data found"
  )
  if (is.null(lcov)) {
    return()
  }

  parse_lcov(
    lcov,
    package_path = c(path, getOption("covr.gcov_additional_paths", NULL))
  )
}

# Parse the line counts of the LCOV tracefile written by `llvm-cov export`,
# keeping the source files in the package, or one of the
# `covr.gcov_additional_paths`, and outside of its Rust dependencies.
parse_lcov <- function(lines, package_path) {
  source_file <- startsWith(lines, "SF:")
  record <- cumsum(source_file)
  files <- substring(lines[source_file], 4)

  line_data <- startsWith(lines, "DA:") & record > 0
  fields <- strsplit(substring(lines[line_data], 4), ",", fixed = TRUE)
  line <- as.integer(vcapply(fields, `[[`, 1))
  count <- as.numeric(vcapply(fields, `[[`, 2))
  by_file <- split(seq_along(line), record[line_data])

  res <- lapply(names(by_file), function(i) {
    source_file <- normalize_path(files[[as.integer(i)]])
    if (!in_package_path(source_file, package_path)) {
      return(NULL)
    }
    if (in_rust_dependency_dir(source_file, package_path)) {
      return(NULL)
    }

    idx <- by_file[[i]]
    line_coverages(
      source_file,
      list(line = line[idx]),
      count[idx],
      rep(NA_character_, length(idx))
    )
  })

  unlist(res, recursive = FALSE)
}
